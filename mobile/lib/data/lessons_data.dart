/// Две «дороги» заданий: математика и финансы.
///
/// Каждое задание — ситуация, четыре варианта ответа кнопками (без
/// клавиатуры), разбор и справка. Задания сгруппированы по классам:
/// по возрасту ребёнку рекомендуется свой класс, но открыты все.
///
/// Тексты финансовой дороги — из методички «Азбука финансов / Мастер
/// накоплений / Вклад в будущее». 4 класс математики — из «Учебника
/// математики». Чтобы дороги не повторяли друг друга, 1–3 классы
/// математики — отдельные примеры по программе этих классов.
enum LessonTrack { math, finance }

extension LessonTrackInfo on LessonTrack {
  String get title {
    switch (this) {
      case LessonTrack.math:
        return 'Математика';
      case LessonTrack.finance:
        return 'Финансы';
    }
  }

  String get emoji {
    switch (this) {
      case LessonTrack.math:
        return '🧮';
      case LessonTrack.finance:
        return '💰';
    }
  }

  /// Цвет дороги: узлы, линия, заголовки разделов.
  Color get color {
    switch (this) {
      case LessonTrack.math:
        return const Color(0xFF2E9BD6);
      case LessonTrack.finance:
        return const Color(0xFFF08A24);
    }
  }

  /// Подпись ступени дороги: у математики — класс, у финансов — уровень
  /// (три раздела на четыре класса).
  String gradeLabel(int grade) =>
      this == LessonTrack.math ? '$grade класс' : '$grade уровень';

  /// Название раздела дороги для класса.
  String sectionTitle(int grade) {
    if (this == LessonTrack.finance) {
      switch (grade) {
        case 1:
          return 'Азбука финансов';
        case 2:
          return 'Мастер накоплений';
        default:
          return 'Вклад в будущее';
      }
    }
    switch (grade) {
      case 1:
        return 'Сложение и вычитание до 20';
      case 2:
        return 'Умножение и деление';
      case 3:
        return 'Остаток, прибыль и проценты';
      default:
        return 'Многошаговые задачи';
    }
  }
}

class Lesson {
  final String id;
  final LessonTrack track;

  /// Класс (1–4): по нему считаем сложность, награду и рекомендацию.
  final int grade;
  final String title;
  final String emoji;
  final String question;

  /// Варианты ответа. Правильный — [correct].
  final List<String> options;
  final int correct;

  /// Разбор решения — показываем после ответа.
  final String answer;

  /// Справка: правило, которое стоит запомнить.
  final String note;

  const Lesson({
    required this.id,
    required this.track,
    required this.grade,
    required this.title,
    required this.emoji,
    required this.question,
    required this.options,
    required this.correct,
    required this.answer,
    required this.note,
  });

  /// Чем старше класс, тем больше монет.
  int get reward => rewardForGrade(grade);
}

/// Награда за задание: 10 / 15 / 20 / 25 монет за 1–4 уровень.
int rewardForGrade(int grade) => 5 + grade * 5;

/// Монеты дают не больше чем за столько заданий за игровой день —
/// чтобы задания не заменяли заботу о питомце и бюджет.
const int rewardedLessonsPerDay = 2;

/// Опыт питомцу за решённое задание.
const int lessonXp = 5;

/// Школьный класс по возрасту: 7 лет — 1 класс, 8 — 2, 9 — 3, 10+ — 4.
int schoolClass(int? age) {
  if (age == null) return 1;
  return (age - 6).clamp(1, 4);
}

/// Какой уровень дороги рекомендуем по возрасту.
///
/// Математика идёт по классам 1–4. У «Финансов» три раздела:
/// 1–2 класс — «Азбука финансов», 3 класс — «Мастер накоплений»,
/// 4 класс — «Вклад в будущее».
int recommendedGrade(int? age, LessonTrack track) {
  final cls = schoolClass(age);
  final grade = track == LessonTrack.finance ? (cls <= 2 ? 1 : cls - 1) : cls;
  final maxGrade = gradesOf(track).last;
  return grade > maxGrade ? maxGrade : grade;
}

List<Lesson> lessonsOf(LessonTrack track) =>
    lessonsCatalog.where((l) => l.track == track).toList();

List<int> gradesOf(LessonTrack track) {
  final grades = lessonsOf(track).map((l) => l.grade).toSet().toList()
    ..sort();
  return grades;
}

Lesson? lessonById(String id) {
  for (final l in lessonsCatalog) {
    if (l.id == id) return l;
  }
  return null;
}

